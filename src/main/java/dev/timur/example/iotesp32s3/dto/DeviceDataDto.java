package dev.timur.example.iotesp32s3.dto;

import lombok.*;

import java.time.LocalDateTime;

/**
 * DTO для передачи данных телеметрии от IoT устройств ESP32S3.
 * Представляет один снимок показаний сенсоров в определенный момент времени.
 * 
 * Поддерживаемые типы данных:
 * - Климатические показатели: температура и влажность
 * - Световые показатели: RGB компоненты и общая яркость
 * - Временная метка для построения временных рядов
 * - Связь с конкретным устройством через deviceId
 * 
 * Особенности:
 * - Оптимизирован для массовой обработки данных временных рядов
 * - Поддерживает JSON сериализацию для REST API
 * - Совместим с аналитическими запросами и агрегациями
 * - Включает все необходимые данные для мониторинга и алертов
 * - Использует Float для точных измерений климатических показателей
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class DeviceDataDto {
    
    /** Уникальный идентификатор записи данных */
    private Long id;
    
    /** Влажность в процентах (0.0-100.0) */
    private Float humidity;
    
    /** Температура в градусах Цельсия */
    private Float temperature;
    
    /** Красный компонент RGB (0-255) */
    private Integer redColor;
    
    /** Зеленый компонент RGB (0-255) */
    private Integer greenColor;
    
    /** Синий компонент RGB (0-255) */
    private Integer blueColor;
    
    /** Общая яркость освещения (0-255 или в люксах) */
    private Integer brightness;
    
    /** Временная метка снятия показаний */
    private LocalDateTime timestamp;
    
    /** Идентификатор устройства, с которого получены данные */
    private Long deviceId;
}
